let currentLang = localStorage.getItem('manpower_lang') || 'en';
window.currentLang = currentLang; // เผื่อไฟล์อื่นเช็คผ่าน window.currentLang

function t(key) {
  return I18N_DICT[currentLang]?.[key] ?? I18N_DICT.th[key] ?? key;
}

function applyLanguage(lang) {
  currentLang = lang;
  window.currentLang = lang;
  localStorage.setItem('manpower_lang', lang);

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    // กัน key ที่เผลอเป็น function (ไม่ควรใช้กับ data-i18n แต่กันไว้ไม่ให้ [object Function] โผล่)
    el.textContent = (typeof val === 'function') ? key : val;
  });

  // รองรับ placeholder ของ input/textarea ผ่าน data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const val = t(key);
    el.setAttribute('placeholder', (typeof val === 'function') ? key : val);
  });

  // 🔧 แก้ไข: เดิมรองรับแค่ th/en — เลือกญี่ปุ่นแล้ว lang กลายเป็น "en" ผิด
  document.documentElement.lang = ['th', 'en', 'ja'].includes(lang) ? lang : 'en';

  // ── re-render หน้าที่มีข้อความ dynamic ที่ผูกกับภาษา ──

  // หน้า Manpower Analytics
  if (typeof window.analyticsApplyFilters === 'function') {
    window.analyticsApplyFilters();
  }
  // 🔧 แก้ไข: dropdown "All codes"/"All factories" ไม่เปลี่ยนภาษาตาม
  // เพราะ populateFilters() (ตัวที่ set ข้อความ default option) ไม่เคย
  // ถูก export/เรียกซ้ำตอนสลับภาษามาก่อน — เพิ่มตรงนี้
  if (typeof window.populateFilters === 'function') {
    window.populateFilters();
  }

  // หน้า Monthly Manpower — re-render โดยไม่ fetch ใหม่ถ้ามีข้อมูลอยู่แล้ว
  if (typeof window.loadData === 'function' && window.State?.lines?.length) {
    window.loadData(window.State.shift || 'ALL');
  }

  // หน้า IE Monthly Report — re-render ตาราง summary ตามสถานะ filter เดือนปัจจุบัน
  const rptMonthSel = document.getElementById('rpt-month-sel');
  if (rptMonthSel) {
    if (rptMonthSel.value && typeof window.renderRptSummary === 'function') {
      window.renderRptSummary();
    } else if (!rptMonthSel.value && typeof window.renderRptSummaryMulti === 'function') {
      window.renderRptSummaryMulti();
    }
  }

  // หน้า Database Manager (Line Master Data / Shift Factor Data) — re-render โดยไม่ fetch ใหม่
  if (typeof window.reRenderDbPages === 'function') {
    window.reRenderDbPages();
  }

  // หน้า Users Management / Activity Log — re-render โดยไม่ fetch ใหม่
  if (typeof window.reRenderUsersLogPages === 'function') {
    window.reRenderUsersLogPages();
  }

  // หน้า Assign Employees — re-render โดยไม่ fetch ใหม่
  if (typeof window.reRenderEmpPage === 'function') {
    window.reRenderEmpPage();
  }

  // หน้า Manpower Planning (รายการแผน/สร้าง-แก้ไขแผน/Board/Compare) — re-render
  // จาก state/cache ที่มีอยู่แล้ว โดยไม่ fetch ใหม่ (ดู window.reRenderPlanningPage
  // ใน planning-manager.js)
  if (typeof window.reRenderPlanningPage === 'function') {
    window.reRenderPlanningPage();
  }

  // แผงแจ้งเตือน — re-render โดยไม่ fetch ใหม่
  if (typeof window.reRenderNotifPanel === 'function') {
    window.reRenderNotifPanel();
  }

  // หน้า Report Adjustment — re-render ตารางจากข้อมูลที่โหลดไว้แล้ว โดยไม่ fetch ใหม่
  if (typeof window.ReportAdjustment?.reRender === 'function') {
    window.ReportAdjustment.reRender();
  }

  // หน้า Manpower Dashboard — re-render KPI/กราฟ/ตาราง/Report view จากข้อมูล
  // ที่โหลดไว้แล้ว โดยไม่ fetch ใหม่ (ดู window.reRenderMpdPage ใน manpower-dashboard.js)
  if (typeof window.reRenderMpdPage === 'function') {
    window.reRenderMpdPage();
  }

  // แชทบอท (Manpower assistant) — re-render header/ปุ่มเมนู/ข้อความ static โดยไม่รีเซ็ตบทสนทนา
  if (typeof window.reRenderChatbotWidget === 'function') {
    window.reRenderChatbotWidget();
  }
}

